#!/usr/bin/env python3
"""Writes ganit's keys from its keymaps (ganit/vim.py) into the two places
that list them: the `# keybind:` lines in ganit/__init__.py (Vayu's keybinding
search reads them) and the key tables in README.md. `--check` fails when
either is out of date (CI runs it).
"""
import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("ganit_vim", ROOT / "ganit" / "vim.py")
vim = importlib.util.module_from_spec(spec)
spec.loader.exec_module(vim)

INSERT = [
    ("<CR>", "Run the sum and keep it on the tape (Convert: save the conversion); stays in insert mode"),
    ("<Esc>", "Enter normal mode, where every other key works"),
]


def groups():
    """(scope, title, [(keys, what)]) in reading order."""
    def part(binds, leader):
        return [(vim.spell(s), d) for s, _, d in binds if s.startswith(vim.LEADER) == leader]
    return [
        ("ganit insert", "Insert mode (typing)", [(vim.spell(s), d) for s, d in INSERT]),
        ("ganit normal", "Normal mode, both tabs", part(vim.COMMON, False)),
        ("ganit calculator", "Normal mode, Calculate", part(vim.CALC, False)),
        ("ganit converter", "Normal mode, Convert", part(vim.CONVERT, False)),
        ("ganit leader", "Leader (Space), both tabs", part(vim.COMMON, True)),
        ("ganit calculator leader", "Leader (Space), Calculate", part(vim.CALC, True)),
        ("ganit converter leader", "Leader (Space), Convert", part(vim.CONVERT, True)),
    ]


def annotations():
    lines = ["# KEYBINDS (generated from ganit/vim.py by scripts/keybinds.py; don't edit by hand)"]
    for scope, _, keys in groups():
        lines += [f"# keybind: Vyom/{scope} | {k} | {d}" for k, d in keys]
    lines.append("# END KEYBINDS")
    return "\n".join(lines) + "\n"


def tables():
    out = ["<!-- KEYS (generated by scripts/keybinds.py from ganit/vim.py) -->", ""]
    for _, title, keys in groups():
        out += [f"**{title}**", "", "| Key | Action |", "|---|---|"]
        out += [f"| `{k}` | {d} |" for k, d in keys]
        out.append("")
    out.append("<!-- END KEYS -->")
    return "\n".join(out)


def splice(text, start, end, new):
    a = text.index(start)
    b = text.index(end, a) + len(end)
    if new.endswith("\n") and text[b:b + 1] == "\n":
        b += 1
    return text[:a] + new + text[b:]


def main():
    init = ROOT / "ganit" / "__init__.py"
    readme = ROOT / "README.md"
    new_init = splice(init.read_text(), "# KEYBINDS", "# END KEYBINDS", annotations())
    new_readme = splice(readme.read_text(), "<!-- KEYS", "<!-- END KEYS -->", tables())
    stale = [p.name for p, t in ((init, new_init), (readme, new_readme)) if p.read_text() != t]
    if "--check" in sys.argv:
        if stale:
            sys.exit(f"out of date: {', '.join(stale)} (run scripts/keybinds.py)")
        print("keys are up to date")
        return
    init.write_text(new_init)
    readme.write_text(new_readme)
    print("wrote", ", ".join(stale) or "nothing (up to date)")


if __name__ == "__main__":
    main()
