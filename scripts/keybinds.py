#!/usr/bin/env python3
"""Writes ganit's keys from its keymap (ganit/vim.py) into the two places
that list them: the `# keybind:` lines in ganit/__init__.py (Vayu's keybinding
search reads them; the mode follows the scope, ":normal" / ":insert") and the
key tables in README.md. `--check` fails when either is out of date (CI runs it).

The keymap uses Vyom's keys module (vyom/keys.py, pure Python): it's found
on PYTHONPATH, in $VYOM_CORE, next to this checkout (../vyom) or in the
installed Vyom (~/.local/share/vyom/core).
"""
import importlib.util
import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def find_vyom():
    try:
        import vyom.keys  # noqa: F401
        return
    except ImportError:
        pass
    for d in (os.environ.get("VYOM_CORE"), ROOT.parent / "vyom",
              pathlib.Path.home() / ".local/share/vyom/core"):
        if d and (pathlib.Path(d) / "vyom" / "keys.py").exists():
            sys.path.insert(0, str(d))
            return
    sys.exit("can't find Vyom's vyom/keys.py: set VYOM_CORE to a Vyom checkout")


find_vyom()
from vyom import keys as K

spec = importlib.util.spec_from_file_location("ganit_vim", ROOT / "ganit" / "vim.py")
vim = importlib.util.module_from_spec(spec)
spec.loader.exec_module(vim)


def groups():
    """(scope, mode, title, [Bind]) in reading order."""
    def part(binds, leader, mode="normal"):
        return [b for b in binds if b.mode == mode and not b.hidden and b.desc
                and b.seq.startswith(K.LEADER) == leader]
    return [
        ("ganit calculator", "insert", "Insert mode (typing), Calculate",
         [b for b in part(vim.INSERT, False, "insert") if b.when in (None, "calc")]),
        ("ganit converter", "insert", "Insert mode (typing), Convert",
         [b for b in part(vim.INSERT, False, "insert") if b.when in (None, "convert")]),
        ("ganit", "normal", "Normal mode, both tabs", part(vim.COMMON, False)),
        ("ganit calculator", "normal", "Normal mode, Calculate", part(vim.CALC, False)),
        ("ganit converter", "normal", "Normal mode, Convert", part(vim.CONVERT, False)),
        ("ganit leader", "normal", "Leader (Space), both tabs", part(vim.COMMON, True)),
        ("ganit calculator leader", "normal", "Leader (Space), Calculate", part(vim.CALC, True)),
        ("ganit converter leader", "normal", "Leader (Space), Convert", part(vim.CONVERT, True)),
    ]


def annotations():
    lines = ["# KEYBINDS (generated from ganit/vim.py by scripts/keybinds.py; don't edit by hand)"]
    lines += K.annotations("Vyom", [(scope, mode, bs) for scope, mode, _, bs in groups()])
    lines.append("# END KEYBINDS")
    return "\n".join(lines) + "\n"


def tables():
    core = ("Vyom's keys work too (every vim tool has them): `?` and `Space ?` list every key, "
            "`Space Space` is the palette, `H` / `L` switch tabs, `q` closes, `Space u f` is fullscreen.")
    out = ["<!-- KEYS (generated by scripts/keybinds.py from ganit/vim.py) -->", "", core, ""]
    for _, _, title, bs in groups():
        out += [f"**{title}**", "", "| Key | Action |", "|---|---|"]
        out += [f"| `{K.spell(b.seq)}` | {b.desc} |" for b in bs]
        out.append("")
    out.append("<!-- END KEYS -->")
    return "\n".join(out)


def splice(text, start, end, new):
    a = text.index(start)
    b = text.index(end, a) + len(end)
    if new.endswith("\n") and text[b:b + 1] == "\n":
        b += 1
    return text[:a] + new + text[b:]


def main():
    init = ROOT / "ganit" / "__init__.py"
    readme = ROOT / "README.md"
    new_init = splice(init.read_text(), "# KEYBINDS", "# END KEYBINDS", annotations())
    new_readme = splice(readme.read_text(), "<!-- KEYS", "<!-- END KEYS -->", tables())
    stale = [p.name for p, t in ((init, new_init), (readme, new_readme)) if p.read_text() != t]
    if "--check" in sys.argv:
        if stale:
            sys.exit(f"out of date: {', '.join(stale)} (run scripts/keybinds.py)")
        print("keys are up to date")
        return
    init.write_text(new_init)
    readme.write_text(new_readme)
    print("wrote", ", ".join(stale) or "nothing (up to date)")


if __name__ == "__main__":
    main()
